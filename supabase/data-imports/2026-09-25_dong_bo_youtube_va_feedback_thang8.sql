with sheet(lop, ngay, url) as (values
 ('DUY-SH','2026-08-24','https://youtu.be/NUg5pHH2luE'),
 ('DUY-SH','2026-08-26','https://youtu.be/sD-JdiZpzq4'),
 ('VY-SH','2026-08-23','https://youtu.be/PiCm2DTMJKE'),
 ('VY-SH','2026-08-25','https://youtu.be/K9aeOvNhz1Q'),
 ('VY-SH','2026-09-13','https://youtu.be/Qq9sbf2D9-s')),
buoi as (
  select s.url, l.id as lesson_id
    from sheet s
    join public.classes c on c.class_code = s.lop
    join public.lessons l on l.class_id=c.id and l.lesson_date = s.ngay::date
)
insert into public.recordings (lesson_id, url, title, status)
select b.lesson_id, b.url,
       'Ban ghi YouTube — dong bo tu bang Nhat ky lop Zoom ngay 25/09/2026', 'active'
  from buoi b
 where not exists (select 1 from public.recordings r
                    where r.lesson_id=b.lesson_id and r.url=b.url);

